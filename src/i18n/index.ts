/** "192.168.20.0/24 (VLAN 20 · PCs)": the network and, when it belongs to one, its VLAN. */
export function netLabel(t: Dict, key: string, tag?: { vlan?: number; name?: string }): string {
  if (tag?.vlan === undefined) return key;
  return `${key} (${fmt(t.policy.vlan, { n: tag.vlan })}${tag.name ? ` · ${tag.name}` : ""})`;
}

export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}
